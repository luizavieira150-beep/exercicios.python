# Exemplo - Média de três notas
# Aluna: Luiza Vieira
# Objetivo: Ler três notas e mostrar a média

nota1 = float(input("Digite sua primeira nota: ")) #usuário digita a nota e ela fica armaenada em nota1
nota2 = float(input("Digite sua segunda nota: ")) #usuário digita a nota e ela fica armaenada em nota2
nota3 = float(input("Digite sua terceira nota: ")) #usuário digita a nota e ela fica armaenada em nota3

media = (nota1 + nota2 + nota3) /3 #soma todas as notas, divide por três e armazena em media

print("Sua média é ", media) #exibe a média
