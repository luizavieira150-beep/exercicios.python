# Objetivo: Ler e informar se é positivo ou negativo

num = float(input("Digite seu número: ")) #lê e armazena em num
if num >= 0: #condição se o número for maior ou igual a zero 
    print ("Número positivo") #escreve positivo
else: 
    print ("Número negativo") #senao escreve negativo
