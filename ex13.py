# Objetivo: Ler a senha e mostrar acesso liberado ou negado

senha=str(input("Digite a sua senha: ")) # digita, lê e armazena em senha

if senha == "senai2026": # condição, se a senha for exatamente igual a senai2026
    print("Acesso liberado") # exibe acesso liberado
else:
    print("Acesso negado") # se não exibe acesso negado