# Objetivo: Ler dois números e mostrar soma, subtração e multipliação

num1 = int(input("Digite o seu primeiro número: ")) #usuário digita o primeiro número e ele fica armazenado no num1
num2 = int(input("Digite o seu segundo número: ")) #usuário digita o segundo número e ele fica armazenado no num2

soma = num1 + num2 #o resultado fica guardado em soma
sub = num1 - num2 #o resultado fica guardado em sub
mult = num1 * num2 #o resultado fica guardado em mult

print("O resultado da soma é", soma) #exibe o resultado da soma
print("O resultado da subtração é", sub) #exibe o resultado da subtração
print("O resultado da multiplicação é", mult) #exibe o resultado da multiplicação