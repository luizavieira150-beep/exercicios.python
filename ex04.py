# Objetivo: Ler a temperatura em graus Celcius e mostrar em Fahrenheit

C = float(input("Digite sua temperatura em graus Celcius: "))#pede a temperatura e armazena em C
F = C * 1.8 + 32 #conta para passar a tempertura de Celcius para Fahrenheit

print("Sua temperatura em Fahrenheit é: ", F, "°F")#exibe a temperatura em Fahrenheit