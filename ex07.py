# Objetivo: Ler a idade e informar se é de maior ou não

idade = float(input("Digite a sua idade: ")) #lê e armazena em idade
if idade >= 18: #condição se idade maior ou igual a 18 exibe "Maior de idade"
    print("Maior de idade") 
else:
    print("Menor de idade") #senão exibe menor de idade