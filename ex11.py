# Objetivo: Ler dois números e informar qual deles é maior

num1 = int(input("Digite seu primeiro número: ")) #digita, lê e armazena em num1
num2 = int(input("Digite seu segundo número: ")) #digita, lê e armazena em num2

if num1 > num2: #condição se o número um for maior que número dois
    print("O número maior é ", num1) #exibe que num1 é maior
else:
    print("O número maior ", num2) #se não exibe que num2 é maior